const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { React, act, create, check, checks, errors, loadComponent, makeClock } = require("./barcode-lifecycle.cjs");

async function singleSelect() {
	const clock = makeClock();
	const Component = loadComponent("components/common/SingleSelect.tsx", clock);
	const items = [
		{ value: "a", label: "Alpha", description: "Utama" },
		{ value: "b", label: "Beta", description: "Kedua" },
		{ value: "c", label: "Gamma", disabled: true },
	];
	const changes = [];
	let props = { items, value: "a", onValueChange: v => changes.push(v), showConfirmButton: true, searchable: true };
	let renderer;
	await act(async () => { renderer = create(React.createElement(Component, props)); });
	const update = async patch => { props = { ...props, ...patch }; await act(async () => renderer.update(React.createElement(Component, props))); };
	const options = () => renderer.root.findAllByType("BouncyPressable").slice(1);
	const trigger = () => renderer.root.findAllByType("BouncyPressable")[0];
	const sheet = () => renderer.root.findByType("Actionsheet");
	const search = () => renderer.root.findByType("SearchBar");
	const selected = () => options().filter(o => o.props.className.includes("border-primary ")).map(o => o.findAllByType("Text")[0].props.children);
	const choose = async label => { const option = options().find(o => o.findAllByType("Text")[0].props.children === label); assert.ok(option); await act(async () => option.props.onPress()); };
	const open = async () => { await act(async () => trigger().props.onPress()); };
	const cancel = async () => { await act(async () => sheet().props.onClose()); };
	const save = async () => { await act(async () => renderer.root.findAllByType("Pressable")[1].props.onPress()); };
	check("controlled trigger label follows value", trigger().findByType("Text").props.children, "Alpha");
	await open();
	check("open initializes draft selection", selected(), ["Alpha"]);
	await choose("Beta");
	check("confirm mode keeps selection local until save", changes, []);
	await update({ items: items.map(i => ({ ...i })), label: "Rerender" });
	check("same controlled value and refreshed items preserve draft", selected(), ["Beta"]);
	await act(async () => search().props.setSearch("kED"));
	check("search matches descriptions ignoring case", options().map(o => o.findAllByType("Text")[0].props.children), ["Beta"]);
	await update({ value: "c" });
	check("external value update preserves active search", search().props.search, "kED");
	await act(async () => search().props.setSearch(""));
	check("external value replaces pending draft", selected(), ["Gamma"]);
	await update({ value: "a" });
	await choose("Gamma");
	check("disabled option cannot change draft", selected(), ["Alpha"]);
	await choose("Beta");
	await cancel();
	check("cancel does not emit draft value", changes, []);
	check("cancel closes sheet", sheet().props.isOpen, false);
	await open();
	check("reopen resets draft from committed value", selected(), ["Alpha"]);
	await choose("Beta");
	await save();
	check("save emits draft once and closes", [changes, sheet().props.isOpen], [["b"], false]);
	await update({ value: "b" });
	check("controlled callback echo updates trigger", trigger().findByType("Text").props.children, "Beta");
	await open();
	await update({ value: undefined });
	check("external form reset to undefined clears draft", selected(), []);
	await save();
	check("undefined draft emits no value", changes, ["b"]);
	await update({ disabled: true });
	await open();
	check("disabled trigger does not open sheet", sheet().props.isOpen, false);
	await update({ disabled: false, showConfirmButton: false, dismissOnSelect: false });
	await open();
	await choose("Alpha");
	check("action picker without value emits selection", changes, ["b", "a"]);
	check("dismissOnSelect false keeps sheet open", sheet().props.isOpen, true);
	check("without controlled value trigger retains placeholder", trigger().findByType("Text").props.children, "Pilih salah satu");
	await cancel();
	await open();
	check("action picker without value resets on reopen", selected(), []);
	await update({ dismissOnSelect: true });
	await choose("Beta");
	check("immediate selection emits before dismiss delay", changes.at(-1), "b");
	await clock.advance(149);
	check("dismiss waits 150ms", sheet().props.isOpen, true);
	await clock.advance(1);
	check("dismiss closes after 150ms", sheet().props.isOpen, false);
	await open();
	await choose("Alpha");
	await cancel();
	await open();
	await clock.advance(200);
	check("cancelled timer cannot close reopened sheet", sheet().props.isOpen, true);
	await update({ items: [{ value: 0, label: "Nol" }, { value: 1, label: "Satu" }], value: 0, showConfirmButton: true });
	check("numeric zero remains a valid selection", selected(), ["Nol"]);
	await choose("Satu");
	await update({ value: 0, label: "Another render" });
	check("numeric same-value rerender preserves draft", selected(), ["Satu"]);
	await update({ value: 1 });
	check("numeric external value updates trigger", trigger().findByType("Text").props.children, "Satu");
	await update({ items: [], value: undefined });
	check("empty options and undefined value render safely", options().length, 0);
	await update({ items, value: "a", showConfirmButton: false });
	await choose("Beta");
	await act(async () => renderer.unmount());
	check("unmount cancels dismiss timer", clock.pending(), 0);
}

async function sortSheet() {
	const Component = loadComponent("components/common/SortActionSheet.tsx", makeClock());
	const changes = [];
	let closes = 0;
	let props = { isOpen: false, onClose: () => closes++, onChange: v => changes.push(v) };
	let renderer;
	await act(async () => { renderer = create(React.createElement(Component, props)); });
	const update = async patch => { props = { ...props, ...patch }; await act(async () => renderer.update(React.createElement(Component, props))); };
	const options = () => renderer.root.findAllByType("Pressable").slice(2);
	const selected = () => options().filter(o => o.props.className.includes("border-primary ")).map(o => o.findAllByType("Text")[0].props.children);
	const choose = async label => { const option = options().find(o => o.findAllByType("Text")[0].props.children === label); assert.ok(option); await act(async () => option.props.onPress()); };
	const save = async () => { await act(async () => renderer.root.findAllByType("Pressable")[1].props.onPress()); };
	const cancel = async () => { await act(async () => renderer.root.findAllByType("Pressable")[0].props.onPress()); };
	await update({ isOpen: true });
	check("sort opens with newest default", selected(), ["Terbaru dibuat"]);
	await choose("A - Z");
	check("sort option remains draft until save", changes, []);
	await update({ title: "Updated title" });
	check("unrelated sort rerender preserves draft", selected(), ["A - Z"]);
	await cancel();
	check("sort cancel emits no change", [changes, closes], [[], 1]);
	await update({ isOpen: false });
	await update({ isOpen: true });
	check("sort reopen discards cancelled draft", selected(), ["Terbaru dibuat"]);
	await choose("Z - A");
	await save();
	check("sort save emits selected value and requests close", [changes, closes], [["z-a"], 2]);
	await update({ isOpen: false, value: "z-a" });
	await update({ isOpen: true });
	check("sort reopen follows committed callback echo", selected(), ["Z - A"]);
	await choose("A - Z");
	await update({ value: "newest" });
	check("external sort value replaces pending draft while open", selected(), ["Terbaru dibuat"]);
	await choose("A - Z");
	await update({ value: "newest", title: "Same sort" });
	check("same external sort value preserves draft", selected(), ["A - Z"]);
	await update({ isOpen: false });
	await update({ value: "z-a" });
	await update({ isOpen: true });
	check("external value changed while closed takes effect on open", selected(), ["Z - A"]);
	await update({ value: undefined });
	check("cleared sort value restores newest default", selected(), ["Terbaru dibuat"]);
	await choose("A - Z");
	await act(async () => renderer.root.findByType("Actionsheet").props.onClose());
	check("backdrop close does not commit draft", changes, ["z-a"]);
	await update({ isOpen: false });
	await update({ isOpen: true });
	check("reopen after backdrop close resets draft", selected(), ["Terbaru dibuat"]);
	await save();
	check("save without option change emits current default", changes, ["z-a", "newest"]);
	await act(async () => renderer.unmount());
}
(async () => {
	const suite = process.argv[2] || "single-select";
	assert.ok(["single-select", "sort"].includes(suite));
	if (suite === "single-select") await singleSelect();
	else await sortSheet();
	check("no React runtime errors or act warnings", errors, []);
	const result = { suite, count: checks.length, checks, errors, scope: "Production component with React 19 test renderer and UI/native/haptic host stubs; no application navigator or native interaction." };
	fs.writeFileSync(path.join(__dirname, `${suite}-results.json`), JSON.stringify(result, null, 2) + "\n");
	console.log(JSON.stringify(result, null, 2));
})().catch(error => { console.error(error); process.exitCode = 1; });

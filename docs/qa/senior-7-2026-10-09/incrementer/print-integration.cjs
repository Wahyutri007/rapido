const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");
const { React, act, create, check, checks, errors, makeClock } = require("../barcode-lifecycle.cjs");
const { load } = require("./lifecycle.cjs");
const files = ["components/custom/Incrementer.tsx", "components/feature/barcode/PrintBarcodeModal.tsx"];
const fingerprint = () => files.map(file => ({ file, sha256: crypto.createHash("sha256").update(fs.readFileSync(file)).digest("hex") }));

(async () => {
	const clock = makeClock();
	const Component = load(files[1], clock);
	const confirmed = [];
	let closeCount = 0;
	let props = { isOpen: true, productName: "Produk A", barcodeValue: "BARCODE-A", defaultCopies: 2, onClose: () => closeCount++, onConfirmPrint: n => confirmed.push(n) };
	let renderer;
	await act(async () => { renderer = create(React.createElement(Component, props)); });
	const update = async patch => { props = { ...props, ...patch }; await act(async () => renderer.update(React.createElement(Component, props))); };
	const counter = () => renderer.root.find(node => typeof node.type === "function" && node.type.name === "Incrementer");
	const count = () => counter().findByType("Text").props.children;
	const step = direction => counter().findAllByType("Button").find(button => button.findByType("ButtonIcon").props.name === direction);
	const pressStep = async direction => { await act(async () => step(direction).props.onPress()); };
	const print = () => renderer.root.findAllByType("Button").find(button => button.props.isLoading !== undefined);
	const pressPrint = async () => { await act(async () => print().props.onPress()); };
	check("dialog uses the actual Incrementer and initial print count", count(), 2);
	await pressStep("plus");
	check("increment updates dialog print count", count(), 3);
	await pressStep("minus");
	check("decrement updates dialog print count", count(), 2);
	await pressStep("plus");
	await pressPrint();
	await pressStep("plus");
	check("pending print quantity cannot be incremented after enqueue", count(), 3);
	check("quantity controls lock during pending print", [step("plus").props.isDisabled, step("minus").props.isDisabled], [true, true]);
	await pressStep("minus");
	check("queued print quantity cannot drift", count(), 3);
	await clock.advance(1000);
	check("confirmation uses the displayed queued quantity", confirmed, [3]);
	check("quantity controls remain locked for success state", [step("plus").props.isDisabled, step("minus").props.isDisabled], [true, true]);
	await clock.advance(1200);
	check("successful print closes exactly once", closeCount, 1);
	await update({ isOpen: false });
	await update({ isOpen: true });
	check("reopen restores default quantity and enables stepper", [count(), Boolean(step("plus").props.isDisabled)], [2, false]);
	await pressStep("minus");
	await pressStep("minus");
	check("dialog minimum is one label", count(), 1);
	await update({ defaultCopies: 998 });
	await pressStep("plus");
	await pressStep("plus");
	check("dialog maximum is 999 labels", count(), 999);
	await pressPrint();
	await update({ isOpen: false });
	await update({ isOpen: true, defaultCopies: 2 });
	await clock.advance(2500);
	check("closed job cannot confirm or close new dialog", [confirmed, closeCount, count()], [[3], 1, 2]);
	await pressStep("plus");
	await update({ productName: "Produk A diperbarui" });
	check("metadata rerender preserves count in actual stepper", count(), 3);
	await pressPrint();
	await update({ barcodeValue: "BARCODE-B" });
	check("new barcode resets count and clears old job", [count(), clock.pending()], [2, 0]);
	await pressPrint();
	await act(async () => renderer.unmount());
	check("unmount clears integrated print timer", clock.pending(), 0);
	await clock.advance(3000);
	check("unmounted print emits no callback", confirmed, [3]);
	check("no React runtime errors or act warnings", errors, []);
	const result = { status: "PASS", count: checks.length, checks, errors, source: fingerprint(), scope: "Production PrintBarcodeModal and Incrementer together in React 19 test renderer. RN/Button/BarcodePreview primitives remain host adapters; no physical printer or native/browser runtime." };
	fs.writeFileSync(path.join(__dirname, "print-integration-results.json"), JSON.stringify(result, null, 2) + "\n");
	console.log(JSON.stringify(result, null, 2));
})().catch(error => {
	const result = { status: "FAIL", checks, source: fingerprint(), message: error.message, actual: error.actual, expected: error.expected };
	if (process.argv.includes("--baseline")) fs.writeFileSync(path.join(__dirname, "print-integration-baseline.json"), JSON.stringify(result, null, 2) + "\n");
	console.error(result);
	process.exitCode = 1;
});

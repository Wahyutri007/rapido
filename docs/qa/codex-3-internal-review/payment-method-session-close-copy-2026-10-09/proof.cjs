const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");
const root = path.resolve(__dirname, "../../../..");
const ts = require(path.join(root, "node_modules/typescript"));
const sha = (bytes) => crypto.createHash("sha256").update(bytes).digest("hex");
const target = "components/feature/manage/settings/PaymentMethodModifyScreen.tsx";
const finalHash = "0451db3bf9f4f29f4f2f4c67814fa788edb4cb56a983824848443a0da1d40d4e";
if (fs.existsSync(path.join(__dirname, "proof.json"))) throw new Error("Proof exists; no overwrite");
const before = fs.readFileSync(path.join(__dirname, "form.before.tsx.txt"), "utf8");
const final = fs.readFileSync(path.join(root, target), "utf8");
const checks = [];
const check = (name, actual, expected) => checks.push({ name, passed: JSON.stringify(actual) === JSON.stringify(expected), actual, expected });
check("Final form matches exact requested hash", sha(final), finalHash);
check("Previously reviewed form has exactly one error confirm label Kembali", (before.match(/confirmText="Kembali"/g) ?? []).length, 1);
const normalize = (source) => ts.createPrinter({ newLine: ts.NewLineKind.LineFeed }).printFile(ts.createSourceFile("Form.tsx", source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX));
check("Full source AST changes only confirm label Kembali to Tutup", normalize(final), normalize(before.replace('confirmText="Kembali"', 'confirmText="Tutup"')));
const result = { status: checks.every((entry) => entry.passed) ? "LABEL_ONLY_PROOF_PASS" : "LABEL_ONLY_PROOF_FAIL", target, baselineHash: sha(before), finalHash: sha(final), pass: checks.filter((entry) => entry.passed).length, fail: checks.filter((entry) => !entry.passed).length, checks };
fs.writeFileSync(path.join(__dirname, "proof.json"), `${JSON.stringify(result, null, 2)}\n`);
fs.writeFileSync(path.join(__dirname, "form.final.tsx.txt"), final);
console.log(JSON.stringify({ status: result.status, pass: result.pass, fail: result.fail, finalHash: result.finalHash }, null, 2));
if (result.fail) process.exitCode = 1;

const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");
const appRoot = path.resolve(__dirname, "../../../..");
const ts = require(path.join(appRoot, "node_modules/typescript"));
const hash = (bytes) => crypto.createHash("sha256").update(bytes).digest("hex");
const target = "components/common/AlertModal.tsx";
const expectedFinal = process.argv[2];
if (!/^[a-f0-9]{64}$/.test(expectedFinal ?? "")) throw new Error("Supply new parent finalSHA256");
const output = path.join(__dirname, "alias-proof.json");
if (fs.existsSync(output)) throw new Error("Alias proof already exists; do not overwrite");
const final = fs.readFileSync(path.join(appRoot, target), "utf8");
const geometryOnly = fs.readFileSync(path.join(__dirname, "AlertModal.geometry-only.tsx.txt"), "utf8");
const checks = [];
const check = (name, actual, expected) => checks.push({ name, passed: JSON.stringify(actual) === JSON.stringify(expected), actual, expected });
check("Final source matches parent new hash", hash(final), expectedFinal);
check("Interim geometry source is exactly reviewed a1d8 bytes", hash(geometryOnly), "a1d806655c404507a9c624f9c98d3b8b68216331bbf37eb16ca1b26e29265443");
const rename = geometryOnly.replace("type AlertModal =", "type AlertModalProps =").replace("React.PropsWithChildren<AlertModal>", "React.PropsWithChildren<AlertModalProps>");
const canonical = (source) => ts.createPrinter({ newLine: ts.NewLineKind.LineFeed }).printFile(ts.createSourceFile("AlertModal.tsx", source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX));
check("Interim AST with only private type declaration and annotation rename matches final", canonical(final), canonical(rename));
const emit = (source) => ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.ReactJSX, esModuleInterop: true } }).outputText;
const interimJs = emit(geometryOnly), finalJs = emit(final);
check("Private type rename emits exactly identical JavaScript", finalJs, interimJs);
const result = { status: checks.every((entry) => entry.passed) ? "TYPE_ONLY_ALIAS_PROOF_PASS" : "TYPE_ONLY_ALIAS_PROOF_FAIL", target, finalSourceHash: hash(final), geometryOnlySourceHash: hash(geometryOnly), emittedJavaScriptSha256: { interim: hash(interimJs), final: hash(finalJs) }, pass: checks.filter((entry) => entry.passed).length, fail: checks.filter((entry) => !entry.passed).length, checks };
fs.writeFileSync(output, `${JSON.stringify(result, null, 2)}\n`);
console.log(JSON.stringify({ status: result.status, pass: result.pass, fail: result.fail, finalSourceHash: result.finalSourceHash, emittedJavaScriptSha256: result.emittedJavaScriptSha256 }, null, 2));
if (result.fail) process.exitCode = 1;
